// Bundles the Afterlife engine (@afterlife/core, MIT) into one file this app can import.
// The engine lives in the sibling repository `infopath-afterlife-app`; this app never edits it.
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const core = resolve(here, process.env.AFTERLIFE_CORE ?? '../../infopath-afterlife-app/packages/core');
const commit = execFileSync('git', ['-C', core, 'rev-parse', '--short', 'HEAD']).toString().trim();

// xsltjs asks for Node's fs and path but never calls them in a browser; the engine ships stubs.
const stubs = {
  name: 'xsltjs-stubs',
  setup(b) {
    b.onResolve({ filter: /^(node:)?(fs|path)$/ }, (a) =>
      /[\\/]node_modules[\\/]xsltjs[\\/]/.test(a.importer)
        ? { path: resolve(core, 'src/render/engine/stubs', a.path.replace('node:', '') + '.ts') }
        : undefined,
    );
  },
};

await build({
  plugins: [stubs],
  entryPoints: [resolve(core, 'src/index.ts')],
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  outfile: resolve(here, '../vendor/afterlife-core.mjs'),
  banner: {
    js: `// @afterlife/core at commit ${commit} (MIT). Generated by scripts/vendor-core.mjs; do not edit.`,
  },
  logLevel: 'warning',
});
console.log(`vendored @afterlife/core at ${commit}`);
